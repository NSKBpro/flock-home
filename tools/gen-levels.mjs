// Generate the curated level pack (src/levels.js).
//
// For each level number we build many solvable candidates and keep the one whose measured
// difficulty is closest to the target in the difficulty curve. Difficulty is measured, not guessed:
//   forced  – fewest wire perches that best play needs (0 = the wire is never needed)
//   greedy  – win rate of a bot that always frees a matching bird when it can, otherwise a random one
//   casual  – same bot, but it only looks for a matching bird half the time
// See docs/GAME_DESIGN.md#difficulty-curve and docs/adr/0005-curated-level-pack.md.
//
// Usage: node tools/gen-levels.mjs [count=100]
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const E = require('../src/engine.js');

const COUNT = +(process.argv[2] || 100);
const OPEN = 1; // nests open at a time (ADR 0005)

// Target for level L. Sawtooth: climbs within each block of ten, Storm on x0, breather on x1.
function spec(L) {
  if (L === 1) return { R: 4, C: 4, birds: 6, colors: 2, f: 0, g: 100, tries: 20 };
  if (L === 2) return { R: 5, C: 4, birds: 9, colors: 2, f: 0, g: 95, tries: 30 };
  if (L === 3) return { R: 5, C: 5, birds: 12, colors: 3, f: 1, g: 90, tries: 60 };
  if (L === 4) return { R: 6, C: 5, birds: 12, colors: 3, f: 1, g: 85, tries: 60 };
  const block = Math.floor((L - 1) / 10);            // 0 for 1–10, 1 for 11–20, …
  const pos = ((L - 1) % 10) + 1;                    // 1..10 within the block
  const storm = pos === 10, breather = pos === 1;
  const tier = Math.min(block, 4);
  const R = [6, 7, 7, 8, 8][tier] + (storm ? 1 : 0);
  const C = [5, 6, 6, 7, 7][tier];
  const colors = Math.min(6, [3, 4, 4, 5, 6][tier] + (storm && tier < 4 ? 1 : 0));
  const baseBirds = [15, 21, 24, 30, 33][tier];
  const climb = Math.max(0, pos - 2);                // 0..8 within the block
  const birds = breather ? baseBirds - 3 : baseBirds + 3 * Math.floor(climb / 3) + (storm ? 3 : 0);
  // greedy-bot win-rate target: lower = more real decisions
  const gTop = [85, 75, 65, 58, 52][tier];
  const g = storm ? Math.max(20, gTop - 35) : breather ? Math.min(95, gTop + 10) : Math.max(25, gTop - 3 * climb);
  const f = storm ? 3 : breather ? 1 : climb >= 2 ? 2 : 1;
  return { R, C, birds, colors, f, g, storm, tries: tier === 0 ? 120 : 70 };
}

function measure(lv) {
  return { f: E.forcedWait(lv, 15000), g: E.botWinRate(lv, 1, 80, 11), c: E.botWinRate(lv, 0.5, 80, 13) };
}

const pack = [];
const t0 = Date.now();
for (let L = 1; L <= COUNT; L++) {
  const sp = spec(L);
  const rand = E.rng(L * 2654435761 + 99);
  let best = null, bestScore = Infinity, valid = 0;
  for (let attempt = 0; attempt < sp.tries * 8 && valid < sp.tries; attempt++) {
    const birds = Math.max(6, sp.birds + 3 * (Math.floor(rand() * 3) - 1) * (attempt % 3 === 0 ? 1 : 0));
    const p = {
      R: sp.R, C: sp.C, birds: Math.min(birds, Math.floor(sp.R * sp.C * 0.8 / 3) * 3), colors: sp.colors,
      d: L <= 2 ? 0 : Math.floor(rand() * 4), block: [0, 0.4, 0.7][Math.floor(rand() * 3)], maxWire: 3, open: OPEN,
    };
    const lv = E.buildCandidate(p, rand);
    if (!lv) continue;
    valid++;
    const m = measure(lv);
    // Forced-wait mismatch weighs most; then the greedy win rate, where "too hard" costs twice
    // as much as "too easy" (frustration loses players faster than boredom); then size.
    const gap = m.g - sp.g;
    const score = 30 * Math.abs(m.f - sp.f) + (gap < 0 ? -2 * gap : gap) + 2 * Math.abs(lv.birds.length - sp.birds) / 3
      + (m.g < 12 ? 200 : 0); // never ship a level the greedy bot almost never wins
    if (score < bestScore) { bestScore = score; best = { lv, m }; }
    if (score < 4) break;
  }
  if (!best) throw new Error(`level ${L}: no valid candidate`);
  const { lv, m } = best;
  pack.push({ s: E.encodeLevel(lv), boss: !!sp.storm, f: m.f, g: m.g, c: m.c });
  console.log(`L${String(L).padStart(3)} ${lv.R}x${lv.C} birds ${String(lv.birds.length).padStart(2)} colours ${sp.colors}` +
    `  forced ${m.f} (want ${sp.f})  greedy ${String(m.g).padStart(3)}% (want ${sp.g})  casual ${String(m.c).padStart(3)}%${sp.storm ? '  STORM' : ''}`);
}

const header = `// GENERATED by tools/gen-levels.mjs — do not edit by hand. Regenerate with: npm run levels
// ${pack.length} levels. Each entry: s = encoded level (see encodeLevel in engine.js), boss = Storm level,
// f = forced wire use, g = greedy-bot win %, c = casual-bot win %.
`;
const body = `const LEVEL_PACK = [\n${pack.map(e => '  ' + JSON.stringify(e)).join(',\n')}\n];\n`;
writeFileSync(new URL('../src/levels.js', import.meta.url), header + body +
  "if (typeof module !== 'undefined') module.exports = { LEVEL_PACK };\n");
console.log(`wrote src/levels.js (${pack.length} levels) in ${((Date.now() - t0) / 1000).toFixed(1)} s`);
